/**
 * Map all fields form one mesh to another.
 *
 * Usage:
 * miniMapAllFields map 
 * miniMapAllFields interpolate -sourceOnly
 * miniMapAllFields <map/interpolate/cellPointInterpolate> <-sourceOnly/null>
 *
 * The argument <map/interpolate/cellPointInterpolate> determines the order of
 * accuracy of the mapping (stored in a meshToMesh object).
 *
 * The option `-sourceOnly` determines which member function of the created
 * meshToMesh object to be used, whether the one that only gets the source
 * field, or the one that gets both source and target fileds. The difference is
 * that in the latter, the field needs to be created beforehand, then it will be
 * modified by the interpolation function.
 *
 * \note: Due to implementation technicalities, we create tha target field
 * beforehand anyway, regardless which interpolation function is going to be
 * used. In any case, the target field values will be overritten and the
 * boundaries are (apparently) re-generated by the interpolation function.
 *
 * \author Maalik (ali@tensorfields.com), BlueRoom, Dublin, Ireland
 * \date 27-01-2025
 */

